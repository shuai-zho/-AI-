# ===================== 1. 算术运算符：+ - * / // % ** =====================
print("===== 算术运算符 =====")
print(10 + 5)    # 加法 -> 15
print(10 - 5)    # 减法 -> 5
print(10 * 5)    # 乘法 -> 50
print(10 / 5)    # 除法（结果始终为浮点数） -> 2.0
print(10 // 4)   # 整除（向下取整） -> 2
print(10 % 3)    # 取余 -> 1
print(2 ** 3)    # 幂运算 -> 8

# 算术运算符优先级：** 最高，其次 * / // %，最后才是 + -
# 0.1 + 10 / 4**2 = 0.1 + 10 / 16 = 0.1 + 0.625 = 0.725
print("0.1 + 10 / 4**2 =", 0.1 + 10 / 4**2)


# ===================== 2. 赋值运算符：= += -= *= /= //= %= **= =====================
print("\n===== 赋值运算符 =====")
num = 85
num += 10    # 等价于 num = num + 10
print("num += 10 后, num =", num)    # 95
num -= 10    # 等价于 num = num - 10
print("num -= 10 后, num =", num)    # 85
num *= 10    # 等价于 num = num * 10
print("num *= 10 后, num =", num)    # 850
num //= 10   # 整除赋值
print("num //= 10 后, num =", num)   # 85
num %= 3     # 取余赋值
print("num %= 3 后, num =", num)     # 1
num **= 3    # 幂赋值
print("num **= 3 后, num =", num)    # 1


# ===================== 3. 比较运算符：== != > >= < <= =====================
# 比较运算的结果都是布尔值（True / False）
print("\n===== 比较运算符 =====")
print(f"10 == 5: {10 == 5}")   # False
print(f"10 != 5: {10 != 5}")   # True
print(f"10 > 5:  {10 > 5}")    # True
print(f"10 >= 5: {10 >= 5}")   # True
print(f"10 < 5:  {10 < 5}")    # False
print(f"10 <= 5: {10 <= 5}")   # False


# ===================== 4. 练习：用比较运算符解决实际问题 =====================
