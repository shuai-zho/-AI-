# 练习1：判断一个整数是否为偶数（偶数能被 2 整除，余数为 0）
num = int(input("请输入一个整数: "))
if num % 2 == 0:
    print(f"{num} 是偶数")
else:
    print(f"{num} 是奇数")

# 练习2：电商支付——判断银行卡余额是否足够
balance = float(input("请输入银行卡余额: "))
payment = float(input("请输入支付金额: "))
if balance >= payment:
    print("余额足够，可以支付")
else:
    print("余额不足，无法支付")

# 练习3：库存判断——判断库存是否足够完成购买
stock = int(input("请输入商品库存数量: "))
purchase = int(input("请输入购买数量: "))
if stock >= purchase:
    print("库存足够，可以购买")
else:
    print("库存不足，无法购买")
